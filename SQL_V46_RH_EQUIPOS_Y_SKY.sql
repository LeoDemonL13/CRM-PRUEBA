drop policy if exists "RH administra resguardos" on public.rh_activos_asignaciones;
create policy "RH administra resguardos" on public.rh_activos_asignaciones for all to authenticated using(exists(select 1 from public.perfiles_usuario p where p.id=auth.uid() and p.activo=true and p.rol in ('administrador','rh'))) with check(exists(select 1 from public.perfiles_usuario p where p.id=auth.uid() and p.activo=true and p.rol in ('administrador','rh')));

