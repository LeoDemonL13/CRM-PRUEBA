create index if not exists rh_activos_asignaciones_fecha_idx on public.rh_activos_asignaciones(fecha_asignacion desc);

create or replace function public.rh_activo_oficina_actualizar_trg()
returns trigger
language plpgsql
set search_path=public
as $$
declare v_ocupado numeric(14,2):=0;
begin
    new.codigo=upper(btrim(coalesce(new.codigo,'')));
    new.nombre=btrim(coalesce(new.nombre,''));
    new.categoria=coalesce(nullif(btrim(coalesce(new.categoria,'')),''),'Otro');
    new.unidad=upper(coalesce(nullif(btrim(coalesce(new.unidad,'')),''),'PIEZA'));
    if new.codigo='' or new.nombre='' then raise exception using errcode='22023',message='Código y nombre son obligatorios.'; end if;
    if new.tipo_control='individual' then new.cantidad_total=1;new.unidad='PIEZA';end if;
    if tg_op='UPDATE' then
        select coalesce(sum(a.cantidad),0) into v_ocupado from public.rh_activos_asignaciones a where a.activo_id=old.id and a.estado in ('asignado','danado','perdido');
        if new.cantidad_total<v_ocupado then raise exception using errcode='22023',message=format('La cantidad total no puede ser menor a %s, porque esa cantidad sigue asignada, dañada o perdida.',v_ocupado);end if;
    end if;
    new.updated_at=now();
    return new;
end;
$$;

drop trigger if exists trg_rh_activo_oficina_actualizar on public.rh_activos_oficina;
create trigger trg_rh_activo_oficina_actualizar before insert or update on public.rh_activos_oficina for each row execute function public.rh_activo_oficina_actualizar_trg();

drop trigger if exists trg_rh_activos_asignaciones_fecha on public.rh_activos_asignaciones;
create trigger trg_rh_activos_asignaciones_fecha before update on public.rh_activos_asignaciones for each row execute function public.rh_actualizar_fecha();

