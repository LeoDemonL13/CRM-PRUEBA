-- V21: crea cabecera e items de una cotización en una sola transacción/llamada.
create or replace function public.crm_crear_cotizacion(
    p_origen text,
    p_prioridad text,
    p_fecha_requerida date,
    p_solicitado_por text,
    p_referencia text,
    p_notas text,
    p_items jsonb
)
returns jsonb
language plpgsql
set search_path=public
as $$
declare
    v_id uuid;
    v_folio text;
    v_count integer := 0;
    v_priority text;
begin
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then
        raise exception 'Selecciona al menos un material para cotizar.';
    end if;

    v_priority := case lower(coalesce(p_prioridad,'normal'))
        when 'critica' then 'critica'
        when 'urgente' then 'urgente'
        when 'alta' then 'alta'
        when 'baja' then 'baja'
        when 'programada' then 'programada'
        else 'normal'
    end;

    v_folio := 'COT-' || to_char(clock_timestamp(),'YYYYMMDD-HH24MISS') || '-' || upper(substr(md5(random()::text),1,3));

    insert into public.co_cotizaciones(
        folio,origen,estado,prioridad,fecha_requerida,solicitado_por,referencia,notas,updated_at
    )
    values(
        v_folio,
        case when p_origen in ('bajo_minimo','manual','proyecto','requisicion') then p_origen else 'bajo_minimo' end,
        'solicitada',
        v_priority,
        p_fecha_requerida,
        nullif(btrim(p_solicitado_por),''),
        nullif(btrim(p_referencia),''),
        nullif(btrim(p_notas),''),
        now()
    )
    returning id into v_id;

    insert into public.co_cotizacion_items(
        cotizacion_id,material_codigo,descripcion,marca,unidad,cantidad,
        almacen_id,almacen_nombre,existencia_actual,stock_minimo,stock_medio,stock_maximo,
        estado,updated_at
    )
    select
        v_id,
        nullif(btrim(x.material_codigo),''),
        nullif(btrim(x.descripcion),''),
        nullif(btrim(x.marca),''),
        nullif(btrim(x.unidad),''),
        greatest(coalesce(x.cantidad,0),0),
        case when coalesce(x.almacen_id,0)>0 then x.almacen_id else null end,
        nullif(btrim(x.almacen_nombre),''),
        greatest(coalesce(x.existencia_actual,0),0),
        greatest(coalesce(x.stock_minimo,0),0),
        greatest(coalesce(x.stock_medio,0),0),
        greatest(coalesce(x.stock_maximo,0),0),
        'pendiente',
        now()
    from jsonb_to_recordset(p_items) as x(
        material_codigo text,
        descripcion text,
        marca text,
        unidad text,
        cantidad numeric,
        almacen_id bigint,
        almacen_nombre text,
        existencia_actual numeric,
        stock_minimo numeric,
        stock_medio numeric,
        stock_maximo numeric
    )
    where nullif(btrim(x.material_codigo),'') is not null
      and nullif(btrim(x.descripcion),'') is not null
      and coalesce(x.cantidad,0) > 0;

    get diagnostics v_count = row_count;
    if v_count = 0 then
        raise exception 'No hay materiales válidos para cotizar.';
    end if;

    return jsonb_build_object(
        'id',v_id,
        'folio',v_folio,
        'estado','solicitada',
        'prioridad',v_priority,
        'items',v_count
    );
end;
$$;
grant execute on function public.crm_crear_cotizacion(text,text,date,text,text,text,jsonb) to authenticated;

