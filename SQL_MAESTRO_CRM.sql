-- V21: actualización de niveles de stock en una sola operación.
create or replace function public.crm_actualizar_niveles_stock_lote(p_items jsonb)
returns integer
language plpgsql
set search_path=public
as $$
declare
    v_updated integer := 0;
begin
    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        return 0;
    end if;

    with payload as (
        select
            nullif(btrim(x.codigo),'') as material_codigo,
            x.almacen_id,
            greatest(coalesce(x.stock_minimo,0),0) as stock_minimo,
            greatest(coalesce(x.stock_medio,0),0) as stock_medio,
            greatest(coalesce(x.stock_maximo,0),0) as stock_maximo
        from jsonb_to_recordset(p_items) as x(
            codigo text,
            almacen_id bigint,
            stock_minimo numeric,
            stock_medio numeric,
            stock_maximo numeric
        )
        where nullif(btrim(x.codigo),'') is not null
          and x.almacen_id is not null
          and x.almacen_id > 0
    ),
    normalized as (
        select
            material_codigo,
            almacen_id,
            stock_minimo,
            least(greatest(stock_medio,stock_minimo),greatest(stock_maximo,stock_minimo)) as stock_medio,
            greatest(stock_maximo,stock_minimo) as stock_maximo
        from payload
    )
    update public.existencias_almacen e
       set stock_minimo = n.stock_minimo,
           stock_medio = n.stock_medio,
           stock_maximo = n.stock_maximo,
           updated_at = now()
      from normalized n
     where e.material_codigo = n.material_codigo
       and e.almacen_id = n.almacen_id;

    get diagnostics v_updated = row_count;
    return v_updated;
end;
$$;
grant execute on function public.crm_actualizar_niveles_stock_lote(jsonb) to authenticated;

