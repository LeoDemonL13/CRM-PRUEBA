-- Aprobar la comparación material por material y convertir proveedores temporales
-- seleccionados en proveedores permanentes.
create or replace function public.co_aprobar_cotizacion(p_cotizacion_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
    v_cot public.co_cotizaciones%rowtype;
    v_item record;
    v_offer public.co_cotizacion_ofertas%rowtype;
    v_provider_id bigint;
    v_provider_name text;
    v_missing integer;
    v_saved integer := 0;
begin
    if not exists(
        select 1 from public.perfiles_usuario p
        where p.id=auth.uid() and p.activo=true and p.rol in ('administrador','compras')
    ) then
        raise exception 'Solo Compras o Administrador puede aprobar una cotización.';
    end if;

    select * into v_cot from public.co_cotizaciones where id=p_cotizacion_id for update;
    if not found then raise exception 'No se encontró la cotización.'; end if;

    select count(*) into v_missing
    from public.co_cotizacion_items
    where cotizacion_id=p_cotizacion_id and oferta_seleccionada_id is null;
    if v_missing>0 then
        raise exception 'Falta seleccionar proveedor para % material(es).',v_missing;
    end if;

    for v_item in
        select id,material_codigo,descripcion,marca,oferta_seleccionada_id
        from public.co_cotizacion_items
        where cotizacion_id=p_cotizacion_id
        order by id
    loop
        select * into v_offer
        from public.co_cotizacion_ofertas
        where id=v_item.oferta_seleccionada_id and cotizacion_item_id=v_item.id
        for update;
        if not found then raise exception 'La oferta seleccionada del material % ya no existe.',v_item.material_codigo; end if;

        v_provider_id := v_offer.proveedor_id;
        if v_provider_id is null then
            v_provider_name := btrim(coalesce(v_offer.proveedor_temporal_nombre,''));
            if v_provider_name='' then raise exception 'La oferta temporal del material % no tiene proveedor.',v_item.material_codigo; end if;

            select id into v_provider_id
            from public.co_proveedores
            where lower(btrim(coalesce(nombre_comercial,razon_social)))=lower(v_provider_name)
               or lower(btrim(razon_social))=lower(v_provider_name)
            order by id limit 1;

            if v_provider_id is null then
                insert into public.co_proveedores(
                    razon_social,nombre_comercial,contacto,email,telefono,categoria,estado,notas
                ) values (
                    v_provider_name,v_provider_name,v_offer.proveedor_temporal_contacto,
                    v_offer.proveedor_temporal_email,v_offer.proveedor_temporal_telefono,
                    'Materiales','activo','Alta automática desde cotización '||v_cot.folio
                ) returning id into v_provider_id;
            end if;

            update public.co_cotizacion_ofertas
            set proveedor_id=v_provider_id,updated_at=now()
            where id=v_offer.id;
        end if;

        insert into public.co_proveedor_materiales(
            proveedor_id,material_codigo,descripcion,marca,precio_unitario,moneda,
            plazo_entrega_dias,cantidad_minima,vigencia_hasta,ultima_cotizacion,
            fuente,activo,notas,updated_at
        ) values (
            v_provider_id,v_item.material_codigo,v_item.descripcion,v_item.marca,
            v_offer.precio_unitario,v_offer.moneda,v_offer.plazo_entrega_dias,
            v_offer.cantidad_minima,v_offer.vigencia_hasta,current_date,
            'cotizacion_aceptada',true,v_offer.observaciones,now()
        )
        on conflict(proveedor_id,material_codigo) do update set
            descripcion=excluded.descripcion,
            marca=excluded.marca,
            precio_unitario=excluded.precio_unitario,
            moneda=excluded.moneda,
            plazo_entrega_dias=excluded.plazo_entrega_dias,
            cantidad_minima=excluded.cantidad_minima,
            vigencia_hasta=excluded.vigencia_hasta,
            ultima_cotizacion=excluded.ultima_cotizacion,
            fuente='cotizacion_aceptada',
            activo=true,
            notas=excluded.notas,
            updated_at=now();

        update public.co_cotizacion_items
        set proveedor_seleccionado_id=v_provider_id,estado='seleccionado',updated_at=now()
        where id=v_item.id;

        update public.co_cotizacion_ofertas
        set estado=case when id=v_offer.id then 'seleccionada' else 'descartada' end,
            updated_at=now()
        where cotizacion_item_id=v_item.id;

        v_saved := v_saved + 1;
    end loop;

    update public.co_cotizaciones
    set estado='aprobada',aprobada_por=auth.uid(),aprobada_at=now(),revisada_por=coalesce(revisada_por,auth.uid()),revisada_at=coalesce(revisada_at,now()),updated_at=now()
    where id=p_cotizacion_id;

    return jsonb_build_object('ok',true,'cotizacion_id',p_cotizacion_id,'folio',v_cot.folio,'materiales',v_saved);
end;
$$;

revoke all on function public.co_aprobar_cotizacion(uuid) from public,anon;
grant execute on function public.co_aprobar_cotizacion(uuid) to authenticated;

