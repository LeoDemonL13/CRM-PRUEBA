create or replace function public.crm_validar_existencia_ubicacion_v2()
returns trigger
language plpgsql
set search_path=public
as $$
declare
    v_partes text[];
    v_base text;
    v_consecutivo integer;
    v_capacidad integer;
begin
    if coalesce(btrim(new.ubicacion),'')='' then
        new.ubicacion:=null;
        return new;
    end if;
    new.ubicacion:=upper(btrim(new.ubicacion));
    v_partes:=regexp_match(new.ubicacion,'^(0[1-9]|1[0-9]|20)-([1-9][0-9]*)-([A-Z])([1-9][0-9]*)$');
    if v_partes is null then
        raise exception 'Ubicación inválida: %. Usa RR-Z-PC, por ejemplo 01-1-A1.',new.ubicacion;
    end if;
    v_base:=v_partes[1]||'-'||v_partes[2]||'-'||v_partes[3];
    v_consecutivo:=v_partes[4]::integer;
    select greatest(1,coalesce(u.capacidad_consecutivos,u.columnas,20)) into v_capacidad
    from public.ubicaciones_almacen u
    where u.almacen_id=new.almacen_id and upper(btrim(u.codigo))=v_base and coalesce(u.estado,'Activo')='Activo'
    limit 1;
    if v_capacidad is null then raise exception 'No existe la estructura % en el almacén %.',v_base,new.almacen_id; end if;
    if v_consecutivo>v_capacidad then raise exception '% admite consecutivos del 1 al %.',v_base,v_capacidad; end if;
    return new;
end;
$$;

