-- Inserta notificaciones de servicios próximos a vencer sin duplicar la alerta diaria.
create or replace function public.co_generar_alertas_servicios()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer := 0;
  v_row record;
begin
  for v_row in
    select s.*
    from public.co_servicios s
    where s.estado = 'activo'
      and s.proxima_fecha_pago <= current_date + s.anticipacion_dias
  loop
    if not exists (
      select 1
      from public.notificaciones_sistema n
      where n.tipo = 'servicio_proximo_pago'
        and n.entidad_id = v_row.id
        and n.created_at::date = current_date
    ) then
      insert into public.notificaciones_sistema(tipo,titulo,mensaje,entidad_id,leida)
      values(
        'servicio_proximo_pago',
        'Pago próximo · ' || v_row.nombre,
        coalesce(v_row.proveedor || ' · ', '') || 'Vence ' || to_char(v_row.proxima_fecha_pago,'DD/MM/YYYY') || ' · Aviso con ' || v_row.anticipacion_dias || ' días de anticipación.',
        v_row.id,
        false
      );
      v_count := v_count + 1;
    end if;
  end loop;
  return v_count;
end;
$$;

