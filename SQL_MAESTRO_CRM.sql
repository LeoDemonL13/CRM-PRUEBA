create or replace function public.crm_sincronizar_ubicacion_estructura_v2()
returns trigger
language plpgsql
set search_path = public
as $$
declare
    v_partes text[];
begin
    new.codigo := upper(btrim(coalesce(new.codigo, '')));
    v_partes := regexp_match(new.codigo, '^(\d{2})-([1-9][0-9]*)-([A-Z])$');

    if v_partes is not null and v_partes[1]::integer between 1 and 20 then
        new.rack_numero := v_partes[1]::integer;
        new.zona_numero := v_partes[2]::integer;
        new.piso_letra := v_partes[3];
        new.filas := 1;
        new.capacidad_consecutivos := greatest(1, coalesce(new.capacidad_consecutivos, new.columnas, 20));
        new.columnas := new.capacidad_consecutivos;
        new.codigo := lpad(new.rack_numero::text, 2, '0') || '-' || new.zona_numero || '-' || new.piso_letra;
    else
        new.rack_numero := null;
        new.zona_numero := null;
        new.piso_letra := null;
        new.capacidad_consecutivos := greatest(1, coalesce(new.capacidad_consecutivos, new.columnas, 20));
    end if;

    return new;
end;
$$;

